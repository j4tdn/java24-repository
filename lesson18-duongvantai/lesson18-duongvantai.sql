CREATE DATABASE lesson18_exam;
USE lesson18_exam;

-- 1. TABLE: T01_CLASS
CREATE TABLE T01_CLASS (
    C01_CLASS_ID INT PRIMARY KEY AUTO_INCREMENT,
    C01_CLASS_NAME VARCHAR(100) NOT NULL,
    C01_CLASS_TEACHER VARCHAR(100)
);

-- 2. TABLE: T02_STUDENT
CREATE TABLE T02_STUDENT (
    C02_STUDENT_ID INT PRIMARY KEY AUTO_INCREMENT,
    C02_STUDENT_NAME VARCHAR(100) NOT NULL,
    C02_STUDENT_GENDER ENUM('Male','Female') NOT NULL,
    C02_CLASS_ID INT,
    CONSTRAINT FK_T01_T02 
    FOREIGN KEY (C02_CLASS_ID) 
    REFERENCES T01_CLASS(C01_CLASS_ID)
);

-- 3. TABLE: T03_RESULT
CREATE TABLE T03_RESULT (
    C03_STUDENT_ID INT,
    C03_SUBJECT VARCHAR(50),
    C03_SCORE DECIMAL(4,2),
    PRIMARY KEY (C03_STUDENT_ID, C03_SUBJECT),
    CONSTRAINT FK_T03_T02 
    FOREIGN KEY (C03_STUDENT_ID) 
    REFERENCES T02_STUDENT(C02_STUDENT_ID)
);
