-- 1. Primary Key của bảng  Result là C03_STUDENT_ID,C03_SUBJECT
-- 2. LIST NAME, GENDER, TEACHER NAME OF ALL STUDNETS
SELECT t02.C02_STUDENT_NAME, t02.C02_STUDENT_GENDER , t01.C01_CLASS_TEACHER FROM T02_STUDENT t02
JOIN T01_CLASS t01 ON t02.C02_CLASS_ID = t01.C01_CLASS_ID;
-- 3.  LIST TEACHER NAME, COUNT NUMBER OF STUDNETS CLASS 12C 
SELECT  t01.C01_CLASS_TEACHER , count(t02.C02_STUDENT_ID) as COUNT_NUMBER
FROM T02_STUDENT t02 
JOIN T01_CLASS t01 
	ON  t02.C02_CLASS_ID = t01.C01_CLASS_ID
    WHERE t01.C01_CLASS_NAME = '12C'
    GROUP BY t01.C01_CLASS_TEACHER;
-- 4.  LIST CLASS NAME, NUMBER OF STUDNETS WHO MATH SCORE & LITERATURE SCORE >= 8
SELECT 
    t01.C01_CLASS_NAME,
    COUNT(DISTINCT t02.C02_STUDENT_ID) AS COUNT_NUMBER
FROM T02_STUDENT t02
JOIN T01_CLASS t01
    ON t02.C02_CLASS_ID = t01.C01_CLASS_ID
JOIN T03_RESULT t03
    ON t02.C02_STUDENT_ID = t03.C03_STUDENT_ID
WHERE 
    (t03.C03_SUBJECT = 'Math' AND t03.C03_SCORE >= 8)
    OR
    (t03.C03_SUBJECT = 'Literature' AND t03.C03_SCORE >= 8)
GROUP BY t01.C01_CLASS_NAME, t02.C02_STUDENT_ID
HAVING COUNT(DISTINCT t03.C03_SUBJECT) = 2;
