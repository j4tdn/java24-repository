	C1004_PROJECT_ID INT,
    C1004_EMPLOYEE_ID INT,
    C1004_ASSIGNMENT_TIME DATETIME,
    C1004_UPDATING_TIME DATETIME,
    C1004_WORKING_HOURS_OLD INT,
    C1004_WORKING_HOURS_NEW INT,
    C1004_TRIGGER_TYPE TEXT
);
DELIMITER $$

CREATE TRIGGER trigger_t1004_after_insert
AFTER INSERT
ON T1004_PROJECT_PERSONNEL FOR EACH ROW
BEGIN
    INSERT INTO T1004_PROJECT_PERSONNEL_TRACE(C1004_PROJECT_ID, C1004_EMPLOYEE_ID, C1004_ASSIGNMENT_TIME, C1004_TRIGGER_TYPE)
    VALUES(NEW.C1004_PROJECT_ID, NEW.C1004_EMPLOYEE_ID, current_timestamp(), 'INSERT');
END$$

