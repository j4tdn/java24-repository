  FROM T1002_EMPLOYEE emp
  JOIN T1002_EMPLOYEE sup
    ON emp.C1002_SUPERVISOR_ID = sup.C1002_EMPLOYEE_ID
 WHERE emp.C1002_SALARY > sup.C1002_SALARY;

